"""Shared launch-script rendering.

Both the ``bash`` backend (which writes the script to disk) and the ``print``
backend (which lets ``start_dry`` show it) render through this module, so a dry
run always shows exactly what ``save_bash`` would write.
"""

from __future__ import annotations

import shutil
from typing import Callable, Sequence

from ..models import Agent
from ..quoting import join_posix, quote_posix, quote_windows
from .terminal import (
    choose_linux_emulator,
    linux_emulator_command,
    macos_osascript_command,
    normalize_windows_args,
)

Which = Callable[[str], str | None]


def _posix_script(
    pairs: Sequence[tuple[Agent, list[str]]],
    run_id: str,
    platform: str,
    cwd: str | None,
    which: Which,
) -> str:
    names = ", ".join((agent.name or agent.role) for agent, _ in pairs)
    lines = [
        "#!/usr/bin/env bash",
        "# Generated by pi-agent-graph. Do not edit by hand.",
        f"# run_id: {run_id}",
        f"# agents: {names}",
        "set -u",
    ]
    if cwd:
        lines.append(f"cd {quote_posix(cwd)} || exit 1")
    for agent, cmd in pairs:
        if platform == "darwin":
            invocation = macos_osascript_command(cmd, agent.cwd)
            lines.append(join_posix(invocation))
            continue
        emulator = choose_linux_emulator(which)
        if emulator is None:
            # No emulator available: run in the background as a last resort.
            lines.append(join_posix(cmd) + " &")
            continue
        invocation = linux_emulator_command(
            emulator, cmd, agent.name or agent.role, agent.cwd
        )
        lines.append(join_posix(invocation) + " &")
    lines.append("")
    return "\n".join(lines) + "\n"


def _windows_script(
    pairs: Sequence[tuple[Agent, list[str]]],
    run_id: str,
    cwd: str | None,
) -> str:
    names = ", ".join((agent.name or agent.role) for agent, _ in pairs)
    lines = [
        "@echo off",
        "REM Generated by pi-agent-graph. Do not edit by hand.",
        f"REM run_id: {run_id}",
        f"REM agents: {names}",
    ]
    if cwd:
        lines.append(f'cd /d "{cwd}"')
    for _agent, cmd in pairs:
        lines.append('start "" ' + quote_windows(normalize_windows_args(cmd)))
    lines.append("")
    return "\r\n".join(lines) + "\r\n"


def render_launch_script(
    agents: Sequence[Agent],
    *,
    run_id: str,
    platform: str,
    cwd: str | None = None,
    which: Which | None = None,
) -> str:
    """Render the launch script for *agents* on *platform*."""
    which = which or shutil.which
    pairs = [(agent, agent.build_argv()) for agent in agents]
    if platform.startswith("win"):
        return _windows_script(pairs, run_id, cwd)
    return _posix_script(pairs, run_id, platform, cwd, which)
