"""The ``bash`` backend: write a reproducible launch script."""

from __future__ import annotations

import shutil
import sys
from pathlib import Path
from typing import Callable, Sequence

from ..models import Agent
from ..quoting import join_posix, quote_posix, quote_windows
from .terminal import (
    choose_linux_emulator,
    linux_emulator_command,
    macos_osascript_command,
    normalize_windows_args,
)
from .types import LaunchOptions, LaunchResult

Which = Callable[[str], str | None]


def _posix_script(
    pairs: Sequence[tuple[Agent, list[str]]],
    run_id: str,
    platform: str,
    cwd: str | None,
    which: Which,
) -> str:
    names = ", ".join((agent.name or agent.role) for agent, _ in pairs)
    lines = [
        "#!/usr/bin/env bash",
        "# Generated by pi-agent-graph. Do not edit by hand.",
        f"# run_id: {run_id}",
        f"# agents: {names}",
        "set -u",
    ]
    if cwd:
        lines.append(f"cd {quote_posix(cwd)} || exit 1")
    for agent, cmd in pairs:
        if platform == "darwin":
            invocation = macos_osascript_command(cmd, agent.cwd)
            lines.append(join_posix(invocation))
            continue
        emulator = choose_linux_emulator(which)
        if emulator is None:
            # No emulator available: run in the background as a last resort.
            lines.append(join_posix(cmd) + " &")
            continue
        invocation = linux_emulator_command(
            emulator, cmd, agent.name or agent.role, agent.cwd
        )
        lines.append(join_posix(invocation) + " &")
    lines.append("")
    return "\n".join(lines) + "\n"


def _windows_script(
    pairs: Sequence[tuple[Agent, list[str]]],
    run_id: str,
    cwd: str | None,
) -> str:
    names = ", ".join((agent.name or agent.role) for agent, _ in pairs)
    lines = [
        "@echo off",
        "REM Generated by pi-agent-graph. Do not edit by hand.",
        f"REM run_id: {run_id}",
        f"REM agents: {names}",
    ]
    if cwd:
        lines.append(f'cd /d "{cwd}"')
    for _agent, cmd in pairs:
        lines.append('start "" ' + quote_windows(normalize_windows_args(cmd)))
    lines.append("")
    return "\r\n".join(lines) + "\r\n"


def render_bash_script(
    agents: Sequence[Agent],
    *,
    run_id: str,
    platform: str,
    cwd: str | None = None,
    which: Which | None = None,
) -> str:
    """Render a launch script for *agents* on *platform*."""
    which = which or shutil.which
    pairs = [(agent, agent.build_argv()) for agent in agents]
    if platform.startswith("win"):
        return _windows_script(pairs, run_id, cwd)
    return _posix_script(pairs, run_id, platform, cwd, which)


class BashBackend:
    name = "bash"

    def __init__(self, which: Which | None = None) -> None:
        self._which = which or shutil.which

    def launch(
        self, agents: list[Agent], options: LaunchOptions, run_id: str
    ) -> LaunchResult:
        assert options.bash_path is not None  # guaranteed by validation
        path = Path(options.bash_path)
        platform = options.platform or sys.platform
        script = render_bash_script(
            agents,
            run_id=run_id,
            platform=platform,
            cwd=options.cwd,
            which=self._which,
        )
        path.parent.mkdir(parents=True, exist_ok=True)
        # newline="" keeps the script's exact line endings: no CRLF mangling of
        # a .sh shebang, and no \r\r\n in a .cmd on Windows.
        path.write_text(script, encoding="utf-8", newline="")
        commands = [agent.build_argv() for agent in agents]
        return LaunchResult(
            run_id=run_id,
            backend=self.name,
            commands=commands,
            agents=list(agents),
            pids=[None] * len(agents),
            path=str(path),
        )
